// Lighter koi for the phone fishing minimap.
//
// Reads Assets/Fish/fish.obj (15,644 triangles), welds vertices that share
// position + normal + UV, simplifies with meshoptimizer while weighting normals
// and UVs (so the painted koi texture and the shading stay put), and writes a
// triangle OBJ in the SAME coordinate frame as the source. The game processes
// it with the source's centre and length (SanctuaryFish.js), so a light fish
// lines up exactly with the full one.
//
// Usage (repo root): node tools/mobile/koi-lite.mjs <in.obj> <out.obj> <targetTriangles> [lockBorder=1]
import fs from "node:fs";
import { OBJLoader } from "three/examples/jsm/loaders/OBJLoader.js";
import { mergeVertices } from "three/examples/jsm/utils/BufferGeometryUtils.js";
import { MeshoptSimplifier } from "meshoptimizer";

const [input, output, targetStr, lockStr] = process.argv.slice(2);
const target = Number(targetStr);
if (!input || !output || !(target > 0)) {
  console.error("usage: koi-lite.mjs <in.obj> <out.obj> <targetTriangles> [lockBorder=1]");
  process.exit(2);
}
const lockBorder = lockStr !== "0";

const group = new OBJLoader().parse(fs.readFileSync(input, "utf8"));
let src = null;
group.traverse((o) => { if (!src && o.isMesh) src = o.geometry; });
if (!src) throw new Error("no mesh in " + input);
for (const k of Object.keys(src.attributes)) if (!["position", "normal", "uv"].includes(k)) src.deleteAttribute(k);
const srcTris = src.attributes.position.count / 3;

const welded = mergeVertices(src, 1e-6);
const pos = welded.attributes.position.array;
const nrm = welded.attributes.normal.array;
const uv = welded.attributes.uv.array;
const n = welded.attributes.position.count;
const attrs = new Float32Array(n * 5);
for (let i = 0; i < n; i++) {
  attrs.set([nrm[i * 3], nrm[i * 3 + 1], nrm[i * 3 + 2], uv[i * 2], uv[i * 2 + 1]], i * 5);
}
await MeshoptSimplifier.ready;
const index = new Uint32Array(welded.index.array);
const [outIdx, err] = MeshoptSimplifier.simplifyWithAttributes(
  index, new Float32Array(pos), 3, attrs, 5,
  [0.25, 0.25, 0.25, 1.0, 1.0], null,
  Math.floor(target) * 3, 0.05, lockBorder ? ["LockBorder"] : [],
);

// Compact: keep only the vertices the simplified triangles use.
// 5 decimals for positions/UVs (fish.obj itself has 4), 4 for unit normals.
const f5 = (x) => +x.toFixed(5), f4 = (x) => +x.toFixed(4);
const remap = new Map();
const vs = [], vts = [], vns = [], fs_ = [];
const vid = (i) => {
  if (!remap.has(i)) {
    remap.set(i, remap.size + 1);
    vs.push(`v ${f5(pos[i * 3])} ${f5(pos[i * 3 + 1])} ${f5(pos[i * 3 + 2])}`);
    vts.push(`vt ${f5(uv[i * 2])} ${f5(uv[i * 2 + 1])}`);
    const l = Math.hypot(nrm[i * 3], nrm[i * 3 + 1], nrm[i * 3 + 2]) || 1;
    vns.push(`vn ${f4(nrm[i * 3] / l)} ${f4(nrm[i * 3 + 1] / l)} ${f4(nrm[i * 3 + 2] / l)}`);
  }
  return remap.get(i);
};
for (let t = 0; t < outIdx.length; t += 3) {
  const a = vid(outIdx[t]), b = vid(outIdx[t + 1]), c = vid(outIdx[t + 2]);
  fs_.push(`f ${a}/${a}/${a} ${b}/${b}/${b} ${c}/${c}/${c}`);
}
const header = [
  `# Light koi for the phone fishing minimap — generated by tools/mobile/koi-lite.mjs`,
  `# from ${input.split("/").pop()} (${srcTris} triangles) -> ${outIdx.length / 3} triangles,`,
  `# meshoptimizer simplifyWithAttributes (normals 0.25, UV 1.0, error ${err.toFixed(4)}${lockBorder ? ", LockBorder" : ""}). Same coordinate frame as the source.`,
  `o koi_lite`,
];
fs.writeFileSync(output, [...header, ...vs, ...vts, ...vns, ...fs_, ""].join("\n"));
console.log(JSON.stringify({ input, output, srcTris, weldedVerts: n, outTris: outIdx.length / 3, outVerts: remap.size, relError: +err.toFixed(5), lockBorder, kb: Math.round(fs.statSync(output).size / 1024) }));
